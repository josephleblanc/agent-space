/**
 * Writes js/env.js from VITE_* process env during .deploy-dist Vercel build.
 * No npm deps — avoids remote Rust/WASM compile (Vercel OOM) while baking InsForge
 * deployment env vars into the static bundle.
 */

const { writeFileSync, mkdirSync } = require("node:fs");
const { resolve } = require("node:path");

const KEYS = ["VITE_VAPI_PUBLIC_KEY", "VITE_INSFORGE_URL"];
const INSFORGE_URL_ALIASES = [
  "VITE_INSFORGE_URL",
  "INSFORGE_URL",
  "OSS_HOST",
  "INSFORGE_OSS_HOST",
];

/** @type {Record<string, string>} */
const values = Object.fromEntries(KEYS.map((key) => [key, ""]));

for (const key of KEYS) {
  if (process.env[key]) {
    values[key] = process.env[key];
  }
}

if (!values.VITE_INSFORGE_URL) {
  for (const alias of INSFORGE_URL_ALIASES) {
    if (process.env[alias]) {
      values.VITE_INSFORGE_URL = process.env[alias];
      break;
    }
  }
}

if (!values.VITE_INSFORGE_URL) {
  const appkey = process.env.INSFORGE_APPKEY || process.env.APPKEY;
  const region = process.env.INSFORGE_REGION || process.env.REGION;
  if (appkey && region) {
    values.VITE_INSFORGE_URL = `https://${appkey}.${region}.insforge.app`;
  }
}

if (!values.VITE_INSFORGE_URL) {
  values.VITE_INSFORGE_URL = "https://6ns446hp.us-west.insforge.app";
}

const outDir = resolve(process.cwd(), "js");
mkdirSync(outDir, { recursive: true });
const outFile = resolve(outDir, "env.js");

const body = `// Generated by scripts/inject-deploy-env.js — do not edit by hand.
window.__ENV__ = Object.assign(window.__ENV__ || {}, ${JSON.stringify(values, null, 2)});
`;

writeFileSync(outFile, body, "utf8");
console.log(
  `[inject-deploy-env] wrote ${outFile} (VITE_INSFORGE_URL=${values.VITE_INSFORGE_URL ? "set" : "missing"}, VITE_VAPI_PUBLIC_KEY=${values.VITE_VAPI_PUBLIC_KEY ? "set" : "missing"})`,
);
